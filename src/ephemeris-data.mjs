// Numerical tables for the ephemeris.
//
// PLANET_ELEMENTS: JPL approximate Keplerian elements, 1800 AD – 2050 AD fit
// (E.M. Standish, "Keplerian Elements for Approximate Positions of the Major
// Planets", JPL/Caltech; Table 1). Units: au, dimensionless, degrees;
// rates per Julian century. "embary" is the Earth–Moon barycenter.
//
// LUNAR_*_SERIES: the full 60-term periodic series of the Moon's longitude
// (Σl) and latitude (Σb) from the ELP-2000 truncation in Meeus,
// Astronomical Algorithms (2nd ed.), ch. 47, tables 47.A and 47.B —
// cross-checked term by term between two independent implementations
// (soniakeys/meeus and pymeeus; zero mismatches in 120 terms). Longitude
// terms whose sine coefficient is zero (pure distance terms) are omitted.
// Entries are [D, M, M', F, coefficient], coefficients in 1e-6 degrees;
// terms with M ≠ 0 are scaled by E^|M| at evaluation.
//
// Both tables are verified against JPL Horizons fixtures in
// ephemeris.test.mts; the fixtures are the authority if these ever drift.

function elements(record) {
  return Object.freeze(record);
}

